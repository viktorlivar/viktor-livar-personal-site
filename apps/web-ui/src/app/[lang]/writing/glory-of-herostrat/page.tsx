import WritingPage from '@/components/WritingPage';
import { getWriting, isLanguage } from '@/content/site';
import type { Metadata } from 'next';
import { notFound } from 'next/navigation';
import styles from './page.module.css';

const writing = getWriting('glory-of-herostrat');

export const metadata: Metadata = { title: writing.title };

export default async function GloryOfHerostratPage({
  params,
}: {
  params: Promise<{ lang: string }>;
}): Promise<React.ReactElement> {
  const { lang } = await params;
  if (!isLanguage(lang)) notFound();

  return (
    <WritingPage language={lang} writing={writing}>
      <div className={styles.content}>
        <p>
          Двері у велику кімнату відчинились, і на порозі з’явилась постать короткого
          лисуватого діда з неприродно залитим обличчям. Він дещо наляканим поглядом оглянув
          довгий стіл у центрі та усіх присутніх, які за ним сиділи, після чого вельми
          невпевнено зробив два кроки вперед. Зачинившись, двері грюкнули у нього за спиною.
          Всі погляди вмить повернулись у його бік. Кілька секунд тривала дещо напружена
          мовчанка, після якої чоловік середніх літ зі смужкою вусів та акуратно зачесаним
          волоссям, який сидів на чолі столу, жестом руки поманив новоприбулого до себе. Той,
          все ще невпевнено ступаючи, покрокував туди, куди його покликали. По дорозі він
          декілька разів поправив свої потріпані спортивні штани, які дуже вирізнялися на фоні
          решти елементів: дорогого костюма, білої сорочки та краватки.
        </p>
        <p>
          — Ну що, — хлопнувши в долоні, гукнув чолов’яга зі смужкою вусів, — дочекались
          нарешті! А то я все думав, коли.
        </p>
        <p>— Добрий. Дєнь.</p>
        <p>— Ми офіційно не знайомі. Адольф, — вусатий чоловік протягнув руку.</p>
        <p>— Владімір.</p>
        <p>
          — Та-та. Владімір. Та, знаємо. Знаємо. Ой, Владімір, ото ти дав. Не думав, що такого,
          як ти, ми ще колись дочекаємось. Але от! Таки дочекались. Ти розумієш, я вже дещо
          нервуюсь, бо там ото все, що ти наробив, розбирають, аналізують, складають докупи.
          Може бути, що ти навіть на моє місце пересядеш. Тому ми тут всі дуже збуджені.
        </p>
        <p>
          Чолов’яга з пишними вусами, який сидів по праву руку від Адольфа, все ніяк не міг
          відірвати погляд від спортивних штанів новоприбулого. Покрутившись кілька секунд на
          місці, він врешті не витримав та запитав:
        </p>
        <p>
          — Слухай, Владімір, а чому в тебе таке-от солідне вбрання, а штани якісь старі
          спортивні? Куди поділись штани від костюма?
        </p>
        <p>— Я. Нє хатєл би. Аб етам. Гаваріть.</p>
        <p>— Та ні, просто цікаво, дивишся отак і…</p>
        <p>
          — Сосо, — невдоволено перебив його Адольф. — Цить. Ми ще встигнемо про то поговорити.
        </p>
        <p>
          — Йосиф, а не Сосо, — роздратовано огризнувся вусатий чоловік, після чого ображено
          пробурмотів собі під ніс: — Я в якийсь момент просто почну казати на тебе Долік.
        </p>
        <p>
          — Так, Сосо, — проігнорувавши невдоволене бурмотіння, заговорив Адольф. — Я зараз
          буду робити реорганізацію. Значить, ти тепер сідаєш по ліву руку від мене, тебе з
          другого місця витіснили. А ти, — звернувся він до лисого чоловіка із куцою борідкою,
          який до цього сидів ліворуч, — вставай і сідай он там, ти тепер не входиш у топ-3.
        </p>
        <p>— Таваріщі, — обурено вигукнув той, — я как представітель…</p>
        <p>
          — Та-та, — перебив його Адольф. — “Таваріщі-таваріщі”, закрийся і звільняй місце.
        </p>
        <p>
          Чоловік із куцою борідкою секунду помовчав, після чого розгублено опустив очі,
          піднявся та пересів.
        </p>
        <p>
          — Отак-от, — посміхнувся Адольф, — одного Владіміра витіснили із топ-3, а іншого
          прийняли. Ну ти сідай-сідай, — кивнув він до новоприбулого, вказуючи на місце справа
          від себе, яке для нього щойно звільнили. — Може, потім сядеш і на моє місце, але поки
          що тут.
        </p>
        <p>Коли всі повмощувались, Сосо зробив ще одну спробу втамувати цікавість:</p>
        <p>— То що там зі штанами, Владімір?</p>
        <p>— Я. Їщо раз гаварю. Я. Нє хатєл би. Ета. Абсуждать.</p>
        <p>— Ну, Сосо, тойво. Ну не дави на нього, хай тут освоїться трохи.</p>
        <p>
          — А ми будемо якось відзначати поповнення? — почулося із віддаленої частини столу.
        </p>
        <p>
          — Навіть якщо будемо, ми тобі, Нерон, все одно співати не дозволимо, — відрізав
          Адольф.
        </p>
        <p>— Та я просто…</p>
        <p>
          — Ага, “просто-просто”, — покривився очільник, після чого повернувся до новоприбулого
          і заговорив жвавим голосом: — Слухай, Владімір, мені от цікаво: дивись, як воно дивно
          склалось — у нас на перших чотирьох позиціях я і троє людей із Москви. У вас там що,
          якийсь завод? У вас що, країна спеціалізується на виготовленні таких ото? Причому
          один ліпший від іншого. Ні, ну серйозно. Був від мене по праву руку один з Москви,
          через трохи часу прийшов інший з Москви і витіснив його, а сьогодні от прийшов ти і
          витіснив усіх. Якщо у вас там є якийсь завод, то він, очевидно, добре прогресує.
        </p>
        <p>— Я. Ні панімаю.</p>
        <p>
          — Та от і я “ні панімаю”. Беруться десь у вас такі знов і знов. І при цьому, що
          цікаво, кожен має зуб на Україну. От прямо кожнісінький. Це прямо от головний пункт
          кожного, хто хоче сюди потрапити.
        </p>
        <p>
          — І кстаті, таваріщ, — раптом, щось собі нагадавши, вигукнув чоловік із куцою
          борідкою, який уважно слухав розмову, — ваше заявлєніє о том што я создал…
        </p>
        <p>
          — Та цить уже! — знову перебив його Адольф. — Ми ще колись до цього питання
          повернемось. А ти, Владімір, таки знай, що тут у багатьох до тебе є зауваження, —
          постукавши новоприбулого по плечу, кинув очільник. — Мені от дуже не подобається твоя
          форма нацизму. Мій от нацизм був прямий, відкритий та гордий. А твій якийсь такий
          противний, ниций і гнилий. Я прямо казав, що хочу почистити генофонд від євреїв, я не
          прикривався чимось там, не казав, що хочу їх звільнити. А ти щось там придумуєш,
          брешеш, боягузливо ховаєшся. У мене, та і в інших, — кивнув він лисому чоловікові із
          квадратною щелепою, — була якась естетика, а у тебе все таке гидке. От неприємно мені
          це, неприємно, що ти так мою спадщину попсував.
        </p>
        <p>— Я. Нє щітаю. Што…</p>
        <p>— Та звісно, “не щітаю што”, звісно, та це стану справ не міняє.</p>
        <p>
          Владімір ображено і разом з тим злякано забився в крісло і опустив голову. Його
          обвислі щоки трусилися від емоцій, що вирували всередині.
        </p>
        <p>
          — Що, не думав, що сюди потрапиш, га? — вгадавши переживання новоприбулого, дещо
          поблажливим тоном відповів Адольф. — Ну, принаймні твій відхід супроводжували яскраві
          історичні події. Події глобального значення. Багато пам’ятних моментів. Особливо мені
          сподобалося те, з яким запалом після перемоги в Україні кричали, — очільник раптом
          набрав повітря в груди і голосно та артистично вигукнув: — СЛАВА УКРАЇНІ! ГЕРОЯМ
          СЛАВА!
        </p>
        <p>
          Після вигуку почулося якесь гуркотіння. Владімір розгублено завмер, боячись підняти
          очі. По кімнаті покотився сміх. Адольф замахав рукою перед обличчям.
        </p>
        <p>— О, — глузливо кинув Сосо, — питання про штани знімається.</p>
      </div>
    </WritingPage>
  );
}
